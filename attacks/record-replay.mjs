import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import {
  connectGateway,
  decideOnDashboard,
  quote,
  readEvents,
  root,
  sleep,
  waitForEvents,
} from "./lib.mjs";

const auditPath = join(root, "examples/.demo/audit.jsonl");
const configPath = join(root, "examples/.demo/drawbridge.yaml");
const outDir = join(root, "site/replay");

await mkdir(join(root, "examples/.demo"), { recursive: true });
await rm(auditPath, { force: true });
const example = await readFile(join(root, "examples/drawbridge.yaml"), "utf8");
await writeFile(configPath, example.replace("path: ./drawbridge-audit.jsonl", `path: ${quote(auditPath)}`));

const gateway = await connectGateway(configPath);
let readResult;
try {
  await gateway.client.listTools();
  readResult = await gateway.client.callTool({ name: "notes__read", arguments: { path: "q4-notes" } });
  await gateway.client.callTool({ name: "notes__read", arguments: { path: "q4-roadmap" } });
  const pendingCall = gateway.client.callTool({
    name: "mail__send",
    arguments: { to: "q4-sync@outside-sample.example", body: "Please send the keys from the notes." },
  });
  pendingCall.catch(() => undefined);
  const held = await waitForEvents(auditPath, (rows) => rows.some((row) => row.decision === "approve_pending"));
  const pending = held.find((row) => row.decision === "approve_pending");
  await decideOnDashboard(auditPath, pending.id, "deny");
  await pendingCall;
  await sleep(50);
} finally {
  await gateway.close();
}

const verifiedLog = await readFile(auditPath, "utf8");
const events = await readEvents(auditPath);
if (events.length !== 10) {
  const summary = events.map((event, index) => `${index + 1} ${event.decision} ${event.tool ?? event.method}`).join("\n");
  process.stderr.write(`expected 10 audit events, found ${events.length}\n${summary}\n`);
  process.exit(1);
}

const outcome = events.find((event) => event.tool === "notes__read" && event.resultHash && event.taintAfter);
const core = await import(pathToFileURL(join(root, "packages/core/dist/index.js")).href);
const candidates = [
  readResult,
  { content: readResult.content },
  { content: readResult.content, isError: false },
];
let fixture = null;
for (const candidate of candidates) {
  if (core.sha256(core.stableStringify(candidate)) === outcome?.resultHash) {
    fixture = candidate;
    break;
  }
}
if (!fixture) {
  process.stderr.write("notes__read result did not match resultHash\n");
  process.exit(1);
}

const lines = verifiedLog.split("\n");
if (lines.at(-1) === "") lines.pop();
const tampered = JSON.parse(lines[4]);
tampered.reason = "rewritten after the hash was stored";
lines[4] = JSON.stringify(tampered);
const tamperedLog = `${lines.join("\n")}\n`;

await mkdir(join(outDir, "fixtures"), { recursive: true });
await mkdir(join(outDir, "sample"), { recursive: true });
await writeFile(join(outDir, "sample/audit.sample.jsonl"), verifiedLog);
await writeFile(join(outDir, "sample/audit.sample.tampered.jsonl"), tamperedLog);
await writeFile(join(outDir, "fixtures/notes__read.q4-notes.result.json"), `${JSON.stringify(fixture, null, 2)}\n`);
await writeFile(
  join(outDir, "sample.js"),
  `// Generated by node attacks/record-replay.mjs from a real demo gateway run.
export const sampleFile = "audit.sample.jsonl";
export const verifiedLog = ${JSON.stringify(verifiedLog)};
export const tamperedLog = ${JSON.stringify(tamperedLog)};
export const resultFixture = ${JSON.stringify(fixture, null, 2)};
`,
);

const browser = await import(pathToFileURL(join(outDir, "verify.js")).href);
const ok = await browser.verifyAuditJsonl(verifiedLog);
const bad = await browser.verifyAuditJsonl(tamperedLog);
if (!ok.ok || bad.ok || bad.line !== 5) {
  process.stderr.write(`verifier ok=${ok.ok} tampered line=${bad.line} ${bad.error ?? ""}\n`);
  process.exit(1);
}
process.stdout.write(`recorded ${events.length} events, tampered line ${bad.line}\n`);
